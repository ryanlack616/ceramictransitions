"""_build_crystal_vr_js.py — emit data/crystal_vr.js (file:// fallback bundle).

The viewer fetches data/crystal_vr.json over HTTP(S). Double-clicking
index.html (file://) blocks that fetch (CORS), so this script wraps the same
dataset in a <script>-loadable JS file the page picks up automatically on
file:// (classic script tags are CORS-exempt).

Rebuild with:  python3 _build_crystal_vr_js.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
src = ROOT / "data" / "crystal_vr.json"
dst = ROOT / "data" / "crystal_vr.js"

with open(src, encoding="utf-8") as f:
    payload = json.load(f)

with open(dst, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by _build_crystal_vr_js.py — do not edit.\n")
    f.write("// file:// fallback bundle: window.CRYSTAL_VR_DATA = crystal_vr.json\n")
    f.write("window.CRYSTAL_VR_DATA = " + json.dumps(payload, ensure_ascii=False) + ";\n")

print(f"Wrote {dst} ({dst.stat().st_size / 1048576:.1f} MB)")